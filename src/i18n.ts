type Lang = keyof typeof translations;
type Key  = keyof typeof translations['en'];

let current: Lang = 'en';
export function setLanguage(lang: Lang) { current = lang; }
export function detectLanguage(locale: string): Lang {
  return locale.toLowerCase().startsWith('es') ? 'es' : 'en';
}
export function t(key: Key): string {
  return (translations[current] as Record<string, string>)[key] ?? (translations.en as Record<string, string>)[key] ?? key;
}
